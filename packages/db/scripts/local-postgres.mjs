const assertAttestation = (runtime, databaseName, role, row, verifyManagedSettings) => {
  const serverMajor = Math.floor(Number(row.serverVersionNumber) / 10_000);
  const mismatches = [
    ["database", row.databaseName === databaseName],
    ["role", row.userName === role],
    ["address", row.serverAddress === HOST],
    ["port", Number(row.serverPort) === PORT],
    ["recovery-state", row.inRecovery === false],
    ["server-major", serverMajor === runtime.major && SUPPORTED_POSTGRES_MAJORS.has(serverMajor)],
    ...(role === ADMIN_ROLE
      ? [
          ["data-directory", row.dataDirectory === runtime.dataDirectoryRealPath],
          ["listen-addresses", row.listenAddresses === HOST],
          ["data-checksums", row.dataChecksums === "on"],
          ["system-identifier", row.systemIdentifier === runtime.marker.systemIdentifier],
          ...(verifyManagedSettings
            ? [
                ["cluster-name", row.clusterName === `rituvia_${runtime.marker.systemIdentifier}`],
                ["socket-directory", row.socketDirectories === socketDirectory],
                ["password-encryption", row.passwordEncryption === "scram-sha-256"],
                ["ssl", row.ssl === "off"],
                ["fsync", row.fsync === "on"],
                ["full-page-writes", row.fullPageWrites === "on"],
                ["statement-timeout", row.statementTimeout === "30s"],
                ["lock-timeout", row.lockTimeout === "10s"],
                ["idle-transaction-timeout", row.idleTransactionTimeout === "30s"],
                ["timezone", row.timezone === "UTC"],
                ["log-connections", row.logConnections === "on"],
                ["log-disconnections", row.logDisconnections === "on"],
                ["log-statement", row.logStatement === "none"],
                ["log-min-messages", row.logMinMessages === "fatal"],
                ["log-min-error-statement", row.logMinErrorStatement === "panic"],
                ["log-error-verbosity", row.logErrorVerbosity === "terse"],
                ["log-parameter-limit", row.logParameterLimit === "0"],
                [
                  "hba-methods",
                  Array.isArray(row.hbaMethods) &&
                    row.hbaMethods.length === 2 &&
                    row.hbaMethods[0] === "reject" &&
                    row.hbaMethods[1] === "scram-sha-256",
                ],
                ["hba-errors", Number(row.hbaErrors) === 0],
              ]
            : []),
        ]
      : []),
  ].filter(([, matches]) => !matches);

  if (mismatches.length > 0) {
    throw genericFailure(
      `Live PostgreSQL server does not match the repository-owned cluster: ${mismatches
        .map(([label]) => label)
        .join(", ")}.`,
    );
  }
};

const connectAttested = async (
  runtime,
  databaseName,
  role = ADMIN_ROLE,
  { verifyManagedSettings = true } = {},
) => {
  const client = createClient(runtime, databaseName, role);
  try {
    await client.connect();
    const result = await client.query(
      role === ADMIN_ROLE
        ? `SELECT current_database() AS "databaseName",
                  current_user AS "userName",
                  host(inet_server_addr()) AS "serverAddress",
                  inet_server_port() AS "serverPort",
                  current_setting('data_directory') AS "dataDirectory",
                  current_setting('listen_addresses') AS "listenAddresses",
                  current_setting('data_checksums') AS "dataChecksums",
                  current_setting('server_version_num') AS "serverVersionNumber",
                  current_setting('cluster_name') AS "clusterName",
                  current_setting('unix_socket_directories') AS "socketDirectories",
                  current_setting('password_encryption') AS "passwordEncryption",
                  current_setting('ssl') AS "ssl",
                  current_setting('fsync') AS "fsync",
                  current_setting('full_page_writes') AS "fullPageWrites",
                  current_setting('statement_timeout') AS "statementTimeout",
                  current_setting('lock_timeout') AS "lockTimeout",
                  current_setting('idle_in_transaction_session_timeout') AS "idleTransactionTimeout",
                  current_setting('timezone') AS "timezone",
                  current_setting('log_connections') AS "logConnections",
                  current_setting('log_disconnections') AS "logDisconnections",
                  current_setting('log_statement') AS "logStatement",
                  current_setting('log_min_messages') AS "logMinMessages",
                  current_setting('log_min_error_statement') AS "logMinErrorStatement",
                  current_setting('log_error_verbosity') AS "logErrorVerbosity",
                  current_setting('log_parameter_max_length_on_error') AS "logParameterLimit",
                  pg_is_in_recovery() AS "inRecovery",
                  (SELECT system_identifier::text FROM pg_control_system()) AS "systemIdentifier",
                  (SELECT array_agg(DISTINCT auth_method ORDER BY auth_method)
                     FROM pg_hba_file_rules WHERE error IS NULL) AS "hbaMethods",
                  (SELECT count(*)::int FROM pg_hba_file_rules WHERE error IS NOT NULL) AS "hbaErrors"`
        : `SELECT current_database() AS "databaseName",
                  current_user AS "userName",
                  host(inet_server_addr()) AS "serverAddress",
                  inet_server_port() AS "serverPort",
                  current_setting('server_version_num') AS "serverVersionNumber",
                  pg_is_in_recovery() AS "inRecovery"`,
    );
    assertAttestation(runtime, databaseName, role, result.rows[0], verifyManagedSettings);
    return client;
  } catch (error) {
    await client.end().catch(() => undefined);
    if (error?.message?.startsWith("Live PostgreSQL")) {
      throw error;
    }
    const code = typeof error?.code === "string" ? ` (${error.code})` : "";
    throw genericFailure(`Repository-owned PostgreSQL server attestation failed${code}.`);
  }
};

