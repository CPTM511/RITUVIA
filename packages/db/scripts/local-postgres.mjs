const processIsProvablyAbsent = (pid) => {
  if (!Number.isSafeInteger(pid) || pid <= 0) return false;
  try {
    process.kill(pid, 0);
    return false;
  } catch (error) {
    return error?.code === "ESRCH";
  }
};

const LOCK_TOKEN_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
const lockOwnerPath = (directory) => path.join(directory, "owner.json");

const readLockOwner = async (directory = lockPath) => {
  const metadata = await lstat(directory);
  return readJson(
    metadata.isDirectory() ? lockOwnerPath(directory) : directory,
    "Local PostgreSQL lifecycle lock",
  );
};

const removeOwnedLockDirectory = async (directory) => {
  await rm(lockOwnerPath(directory), { force: true });
  await rmdir(directory);
};

const releaseLifecycleLock = async (token, { preserveReleaseDirectory = false } = {}) => {
  const lock = await readLockOwner();
  if (lock.token !== token || lock.pid !== process.pid) {
    throw genericFailure("Local PostgreSQL lifecycle lock ownership changed unexpectedly.");
  }

  const releasePath = path.join(localRoot, `.lifecycle-lock-release-${token}`);
  await rename(lockPath, releasePath);
  const releasedLock = await readLockOwner(releasePath);
  if (releasedLock.token !== token || releasedLock.pid !== process.pid) {
    throw genericFailure("Released PostgreSQL lifecycle lock ownership is invalid.");
  }
  if (!preserveReleaseDirectory) {
    await removeOwnedLockDirectory(releasePath);
  }
  return releasePath;
};

const acquireLifecycleLock = async (token, mayReclaimStaleLock = true) => {
  const candidatePath = path.join(localRoot, `.lifecycle-lock-candidate-${token}`);
  await mkdir(candidatePath, { mode: 0o700 });
  await writeFile(
    lockOwnerPath(candidatePath),
    `${JSON.stringify({ acquiredAt: new Date().toISOString(), pid: process.pid, token })}\n`,
    { encoding: "utf8", flag: "wx", mode: 0o600 },
  );

  try {
    await rename(candidatePath, lockPath);
    return;
  } catch (error) {
    await rm(candidatePath, { force: true, recursive: true }).catch(() => undefined);
    if (["EEXIST", "ENOTEMPTY"].includes(error?.code) && mayReclaimStaleLock) {
      const existingLock = await readLockOwner();
      if (
        typeof existingLock.acquiredAt === "string" &&
        LOCK_TOKEN_PATTERN.test(existingLock.token ?? "") &&
        processIsProvablyAbsent(existingLock.pid)
      ) {
        const quarantinePath = path.join(
          localRoot,
          `.lifecycle-lock-reclaimed-${existingLock.token}`,
        );
        try {
          await rename(lockPath, quarantinePath);
        } catch {
          throw genericFailure(
            "Another local PostgreSQL lifecycle operation holds the repository lock.",
          );
        }
        return acquireLifecycleLock(token, false);
      }
    }
    throw genericFailure("Another local PostgreSQL lifecycle operation holds the repository lock.");
  }
};

const withLifecycleLock = async (operation) => {
  await ensureLocalRoot();
  const token = randomUUID();
  await acquireLifecycleLock(token);

  let result;
  let primaryError;
  try {
    result = await operation();
  } catch (error) {
    primaryError = error;
  }

  let cleanupError;
  try {
    await releaseLifecycleLock(token);
  } catch (error) {
    cleanupError = error;
  }

  if (primaryError !== undefined) {
    if (
      cleanupError !== undefined &&
      primaryError instanceof Error &&
      primaryError.cause === undefined
    ) {
      primaryError.cause = cleanupError;
    }
    throw primaryError;
  }

  if (cleanupError !== undefined) throw cleanupError;
  return result;
};

export const verifyInterruptedLifecycleLockRelease = async () => {
  await ensureLocalRoot();
  const token = randomUUID();
  await acquireLifecycleLock(token);
  const releasePath = await releaseLifecycleLock(token, { preserveReleaseDirectory: true });
  let entered = false;
  try {
    await withLifecycleLock(async () => {
      entered = true;
    });
  } finally {
    await removeOwnedLockDirectory(releasePath);
  }
  if (!entered) {
    throw genericFailure("Interrupted lifecycle lock release blocked the next operation.");
  }
};

export const verifyStaleLifecycleLockRecovery = async () => {
  await ensureLocalRoot();
  const staleToken = randomUUID();
  const quarantinePath = path.join(localRoot, `.lifecycle-lock-reclaimed-${staleToken}`);
  await mkdir(lockPath, { mode: 0o700 });
  await writeFile(
    lockOwnerPath(lockPath),
    `${JSON.stringify({
      acquiredAt: "2000-01-01T00:00:00.000Z",
      pid: 2_147_483_647,
      token: staleToken,
    })}\n`,
    { encoding: "utf8", flag: "wx", mode: 0o600 },
  );
  let activeOperations = 0;
  let overlapDetected = false;
  let markOperationEntered;
  let releaseOperation;
  const operationEntered = new Promise((resolve) => {
    markOperationEntered = resolve;
  });
  const operationRelease = new Promise((resolve) => {
    releaseOperation = resolve;
  });
  const settleWithin = async (promise, milliseconds) => {
    let timeout;
    try {
      return await Promise.race([
        promise,
        new Promise((resolve) => {
          timeout = setTimeout(() => resolve("timeout"), milliseconds);
        }),
      ]);
    } finally {
      clearTimeout(timeout);
    }
  };
  const contender = () =>
    withLifecycleLock(async () => {
      activeOperations += 1;
      overlapDetected ||= activeOperations > 1;
      markOperationEntered("entered");
      await operationRelease;
      activeOperations -= 1;
    });
  const attempts = [contender(), contender()];
  const attemptSettlements = attempts.map((attempt) =>
    attempt.then(
      () => "fulfilled",
      () => "rejected",
    ),
  );
  const entryState = await settleWithin(operationEntered, 2_000);
  const firstSettlement =
    entryState === "entered"
      ? await settleWithin(Promise.race(attemptSettlements), 2_000)
      : "timeout";
  releaseOperation();
  const outcomes = await Promise.allSettled(attempts);
  await rm(quarantinePath, { force: true, recursive: true });
  try {
    const remainingLock = await readLockOwner();
    if (remainingLock.token === staleToken) {
      await removeOwnedLockDirectory(lockPath);
    }
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (
    entryState !== "entered" ||
    firstSettlement !== "rejected" ||
    overlapDetected ||
    outcomes.filter(({ status }) => status === "fulfilled").length !== 1 ||
    outcomes.filter(({ status }) => status === "rejected").length !== 1
  ) {
    throw genericFailure("Stale lifecycle lock recovery allowed overlapping operations.");
  }
};

const recreateDatabase = async (runtime, databaseName) => {
  if (databaseName !== DEVELOPMENT_DATABASE && !TEST_DATABASE_PATTERN.test(databaseName)) {
    throw genericFailure("Database recreation target is not allowed.");
  }
  const admin = await connectAttested(runtime, "postgres");
  try {
    const target = await admin.query(
      "SELECT pg_get_userbyid(datdba) AS owner FROM pg_database WHERE datname = $1",
      [databaseName],
    );
    if (target.rowCount !== 1 || target.rows[0]?.owner !== MIGRATOR_ROLE) {
      throw genericFailure("Database recreation target owner is unexpected.");
    }
    await admin.query(
      "SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = $1 AND pid <> pg_backend_pid()",
      [databaseName],
    );
    await admin.query(`DROP DATABASE ${databaseName}`);
    await admin.query(`CREATE DATABASE ${databaseName} OWNER ${MIGRATOR_ROLE}`);
    await admin.query(`REVOKE ALL ON DATABASE ${databaseName} FROM PUBLIC`);
  } finally {
    await admin.end();
  }
  await ensureRuntimeDatabasePrivileges(runtime, databaseName);
};

export const resetDevelopmentDatabase = async (runtime, confirmation) => {
  const databaseUrl = buildDatabaseUrl(runtime, DEVELOPMENT_DATABASE);
  assertExactLocalDatabaseUrl(databaseUrl, DEVELOPMENT_DATABASE, runtime.credentials.appPassword);

  if (
    process.env.APP_ENV !== "local" ||
    confirmation !== RESET_CONFIRMATION ||
    (process.env.DATABASE_URL !== undefined && process.env.DATABASE_URL !== databaseUrl)
  ) {
    throw genericFailure("Local database reset confirmation or environment guard failed.");
  }

  await recreateDatabase(runtime, DEVELOPMENT_DATABASE);
  return databaseUrl;
};

