const runCli = async () => {
  const [command, ...args] = process.argv.slice(2);
  if (command === undefined) return false;

  if (command === "start") {
    await withLifecycleLock(async () => {
      const runtime = await loadRuntime();
      const started = await startRuntime(runtime);
      process.stdout.write(
        started
          ? "Started repository-owned PostgreSQL.\n"
          : "PostgreSQL already running and attested.\n",
      );
    });
    return true;
  }

  if (command === "stop") {
    await withLifecycleLock(async () => {
      const runtime = await loadRuntime({ initialize: false });
      const stopped = await stopRuntime(runtime);
      process.stdout.write(
        stopped ? "Stopped repository-owned PostgreSQL.\n" : "PostgreSQL is not running.\n",
      );
    });
    return true;
  }

  if (command === "status" || command === "url") {
    const runtime = await loadRuntime({ initialize: false });
    if (!isClusterRunning(runtime)) {
      throw genericFailure("Repository-owned PostgreSQL is not running.");
    }
    const admin = await connectAttested(runtime, "postgres");
    await admin.end();
    if (command === "status") {
      process.stdout.write(
        `PostgreSQL ${runtime.major} is running at ${HOST}:${PORT} and attested.\n`,
      );
    } else if (args.includes("--reveal")) {
      process.stdout.write(`${buildDatabaseUrl(runtime, DEVELOPMENT_DATABASE)}\n`);
    } else {
      process.stdout.write(
        `Local database URL is stored in ${databaseUrlPath} (mode 0600). Pass --reveal to print it.\n`,
      );
    }
    return true;
  }

  throw genericFailure("Unknown local PostgreSQL command.");
};

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  runCli().catch((error) => {
    process.stderr.write(
      `${error instanceof Error ? error.message : "Local PostgreSQL command failed."}\n`,
    );
    process.exitCode = 1;
  });
}
