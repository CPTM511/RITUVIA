const genericFailure = (message) => new Error(message);

const assertNotSymlink = async (targetPath, label) => {
  try {
    const metadata = await lstat(targetPath);
    if (metadata.isSymbolicLink()) {
      throw genericFailure(`${label} must not be a symbolic link.`);
    }
  } catch (error) {
    if (error?.code !== "ENOENT") {
      throw error;
    }
  }
};

const assertRestrictedMode = async (targetPath, maximumMode, label) => {
  const metadata = await stat(targetPath);
  const actualMode = metadata.mode & 0o777;
  if ((actualMode & ~maximumMode) !== 0) {
    throw genericFailure(`${label} permissions are too broad.`);
  }
};

