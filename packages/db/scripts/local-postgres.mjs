const assertBaseCredentials = (credentials) => {
  const secretPattern = /^[A-Za-z0-9_-]{43}$/;
  if (
    typeof credentials !== "object" ||
    credentials === null ||
    !secretPattern.test(credentials.adminPassword ?? "") ||
    !secretPattern.test(credentials.appPassword ?? "")
  ) {
    throw genericFailure("Local PostgreSQL credentials are invalid.");
  }
};

const assertCredentials = (credentials) => {
  const secretPattern = /^[A-Za-z0-9_-]{43}$/;
  assertBaseCredentials(credentials);
  if (
    !secretPattern.test(credentials.controlPassword ?? "") ||
    !secretPattern.test(credentials.paymentWebhookPassword ?? "") ||
    !secretPattern.test(credentials.privacyDeletionPassword ?? "") ||
    !secretPattern.test(credentials.adminServicePassword ?? "") ||
    !secretPattern.test(credentials.migratorPassword ?? "")
  ) {
    throw genericFailure("Local PostgreSQL credentials are invalid.");
  }
};

const upgradeCredentials = async () => {
  const existing = await readJson(credentialsPath, "Local PostgreSQL credentials");
  assertBaseCredentials(existing);
  const secretPattern = /^[A-Za-z0-9_-]{43}$/;
  const upgraded = {
    adminPassword: existing.adminPassword,
    appPassword: existing.appPassword,
    controlPassword: secretPattern.test(existing.controlPassword ?? "")
      ? existing.controlPassword
      : randomBytes(32).toString("base64url"),
    paymentWebhookPassword: secretPattern.test(existing.paymentWebhookPassword ?? "")
      ? existing.paymentWebhookPassword
      : randomBytes(32).toString("base64url"),
    privacyDeletionPassword: secretPattern.test(existing.privacyDeletionPassword ?? "")
      ? existing.privacyDeletionPassword
      : randomBytes(32).toString("base64url"),
    adminServicePassword: secretPattern.test(existing.adminServicePassword ?? "")
      ? existing.adminServicePassword
      : randomBytes(32).toString("base64url"),
    migratorPassword: secretPattern.test(existing.migratorPassword ?? "")
      ? existing.migratorPassword
      : randomBytes(32).toString("base64url"),
  };
  assertCredentials(upgraded);
  if (
    upgraded.controlPassword !== existing.controlPassword ||
    upgraded.paymentWebhookPassword !== existing.paymentWebhookPassword ||
    upgraded.privacyDeletionPassword !== existing.privacyDeletionPassword ||
    upgraded.adminServicePassword !== existing.adminServicePassword ||
    upgraded.migratorPassword !== existing.migratorPassword
  ) {
    await writeManagedFileAtomically(
      credentialsPath,
      `${JSON.stringify(upgraded, null, 2)}\n`,
      "Local PostgreSQL credential file",
    );
  }
};

const initializeCluster = async (toolchain) => {
  await ensureLocalRoot();
  await assertNotSymlink(dataDirectory, "Local PostgreSQL data directory");
  await assertNotSymlink(credentialsPath, "Local PostgreSQL credential file");

  let dataExists = true;
  let credentialsExist = true;
  try {
    await access(dataDirectory);
  } catch {
    dataExists = false;
  }
  try {
    await access(credentialsPath);
  } catch {
    credentialsExist = false;
  }

  if (dataExists || credentialsExist) {
    if (!dataExists || !credentialsExist) {
      throw genericFailure(
        "Partial local PostgreSQL state requires manual review; no files were deleted.",
      );
    }
    const running =
      runCommand(toolchain.binaries.pg_ctl, ["status", "--pgdata", dataDirectory], {
        allowFailure: true,
      }).status === 0;
    if (!running) {
      const existingMarker = await readJson(markerPath, "Local PostgreSQL cluster marker");
      if (typeof existingMarker.systemIdentifier !== "string") {
        throw genericFailure("Local PostgreSQL cluster marker is invalid.");
      }
      await writeManagedClusterConfiguration(existingMarker.systemIdentifier);
    }
    await upgradeCredentials();
    return;
  }

  const credentials = await createCredentials();
  const bootstrapPasswordPath = path.join(localRoot, `.bootstrap-password-${process.pid}`);
  await writeFile(bootstrapPasswordPath, `${credentials.adminPassword}\n`, {
    encoding: "utf8",
    flag: "wx",
    mode: 0o600,
  });

  try {
    runCommand(toolchain.binaries.initdb, [
      "--auth-host=scram-sha-256",
      "--auth-local=scram-sha-256",
      "--data-checksums",
      `--pgdata=${dataDirectory}`,
      "--encoding=UTF8",
      "--no-locale",
      `--pwfile=${bootstrapPasswordPath}`,
      `--username=${ADMIN_ROLE}`,
    ]);
  } finally {
    await rm(bootstrapPasswordPath, { force: true });
  }

  const systemIdentifier = parseSystemIdentifier(
    runCommand(toolchain.binaries.pg_controldata, [dataDirectory]).stdout,
  );
  await writeManagedClusterConfiguration(systemIdentifier);
  const marker = {
    version: CLUSTER_MARKER_VERSION,
    repositoryRealPath: await realpath(repositoryRoot),
    dataDirectoryRealPath: await realpath(dataDirectory),
    systemIdentifier,
    postgresMajor: toolchain.major,
    host: HOST,
    port: PORT,
  };
  await writeFile(markerPath, `${JSON.stringify(marker, null, 2)}\n`, {
    encoding: "utf8",
    flag: "wx",
    mode: 0o600,
  });
};

const loadRuntime = async ({ initialize = true } = {}) => {
  const toolchain = await resolvePostgresBinaries();
  if (initialize) {
    await initializeCluster(toolchain);
  }

  await assertNotSymlink(dataDirectory, "Local PostgreSQL data directory");
  await assertNotSymlink(credentialsPath, "Local PostgreSQL credential file");
  await assertNotSymlink(markerPath, "Local PostgreSQL marker file");
  await assertNotSymlink(socketDirectory, "Local PostgreSQL socket directory");
  await assertNotSymlink(logPath, "Local PostgreSQL log file");
  await assertNotSymlink(databaseUrlPath, "Local database URL file");
  await assertNotSymlink(path.join(dataDirectory, "pg_hba.conf"), "Local PostgreSQL HBA file");
  await assertNotSymlink(
    path.join(dataDirectory, "postgresql.auto.conf"),
    "Local PostgreSQL managed configuration",
  );

  const hbaPath = path.join(dataDirectory, "pg_hba.conf");
  const autoConfigurationPath = path.join(dataDirectory, "postgresql.auto.conf");
  const [
    credentials,
    marker,
    repositoryRealPath,
    dataDirectoryRealPath,
    pgVersion,
    hbaConfiguration,
    postgresConfiguration,
  ] = await Promise.all([
    readJson(credentialsPath, "Local PostgreSQL credentials"),
    readJson(markerPath, "Local PostgreSQL cluster marker"),
    realpath(repositoryRoot),
    realpath(dataDirectory),
    readFile(path.join(dataDirectory, "PG_VERSION"), "utf8"),
    readFile(hbaPath, "utf8"),
    readFile(autoConfigurationPath, "utf8"),
  ]);
  assertCredentials(credentials);

  const currentSystemIdentifier = parseSystemIdentifier(
    runCommand(toolchain.binaries.pg_controldata, [dataDirectory]).stdout,
  );
  const expectedMarker =
    marker.version === CLUSTER_MARKER_VERSION &&
    marker.repositoryRealPath === repositoryRealPath &&
    marker.dataDirectoryRealPath === dataDirectoryRealPath &&
    marker.systemIdentifier === currentSystemIdentifier &&
    marker.postgresMajor === toolchain.major &&
    marker.host === HOST &&
    marker.port === PORT &&
    Number(pgVersion.trim().split(".")[0]) === toolchain.major &&
    hbaConfiguration === expectedHbaConfiguration() &&
    postgresConfiguration === expectedPostgresConfiguration(marker.systemIdentifier);

  if (!expectedMarker) {
    throw genericFailure("Local PostgreSQL cluster marker does not match this repository/runtime.");
  }

  await Promise.all([
    assertRestrictedMode(localRoot, 0o700, "Local PostgreSQL state directory"),
    assertRestrictedMode(dataDirectory, 0o700, "Local PostgreSQL data directory"),
    assertRestrictedMode(credentialsPath, 0o600, "Local PostgreSQL credential file"),
    assertRestrictedMode(markerPath, 0o600, "Local PostgreSQL marker file"),
    assertRestrictedMode(hbaPath, 0o600, "Local PostgreSQL HBA file"),
    assertRestrictedMode(autoConfigurationPath, 0o600, "Local PostgreSQL managed configuration"),
  ]);

  return Object.freeze({
    ...toolchain,
    credentials: Object.freeze(credentials),
    marker: Object.freeze(marker),
    repositoryRealPath,
    dataDirectoryRealPath,
  });
};

const buildDatabaseUrl = (runtime, databaseName, role = APP_ROLE) => {
  const url = new URL("postgresql://127.0.0.1");
  url.username = role;
  const passwords = {
    [ADMIN_ROLE]: runtime.credentials.adminPassword,
    [APP_ROLE]: runtime.credentials.appPassword,
    [CONTROL_ROLE]: runtime.credentials.controlPassword,
    [PAYMENT_WEBHOOK_ROLE]: runtime.credentials.paymentWebhookPassword,
    [PRIVACY_DELETION_ROLE]: runtime.credentials.privacyDeletionPassword,
    [ADMIN_SERVICE_ROLE]: runtime.credentials.adminServicePassword,
    [MIGRATOR_ROLE]: runtime.credentials.migratorPassword,
  };
  const password = passwords[role];
  if (password === undefined) {
    throw genericFailure("Local database role is not an approved login role.");
  }
  url.password = password;
  url.hostname = HOST;
  url.port = String(PORT);
  url.pathname = `/${databaseName}`;
  for (const [key, value] of Object.entries(SAFE_QUERY_PARAMETERS)) {
    url.searchParams.set(key, value);
  }
  return url.toString();
};

export const assertExactLocalDatabaseUrl = (
  databaseUrl,
  expectedDatabase,
  expectedPassword,
  expectedRole = APP_ROLE,
) => {
  try {
    const parsed = new URL(databaseUrl);
    const entries = Object.fromEntries(parsed.searchParams.entries());
    const expectedEntries = SAFE_QUERY_PARAMETERS;
    if (
      parsed.protocol !== "postgresql:" ||
      parsed.hostname !== HOST ||
      parsed.port !== String(PORT) ||
      parsed.username !== expectedRole ||
      parsed.password !== expectedPassword ||
      parsed.pathname !== `/${expectedDatabase}` ||
      parsed.hash !== "" ||
      parsed.searchParams.size !== Object.keys(expectedEntries).length ||
      Object.entries(expectedEntries).some(([key, value]) => entries[key] !== value)
    ) {
      throw genericFailure("Local database target did not pass the exact-target guard.");
    }
  } catch {
    throw genericFailure("Local database target did not pass the exact-target guard.");
  }
};

