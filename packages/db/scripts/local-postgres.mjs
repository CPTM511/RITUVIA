export const verifyLogicalDumpRestore = async (runtime, sourceHandle, targetHandle) => {
  const sourceDatabase = sourceHandle?.databaseName;
  const targetDatabase = targetHandle?.databaseName;
  if (
    !invocationOwnedTestDatabases.has(sourceHandle) ||
    !invocationOwnedTestDatabases.has(targetHandle) ||
    !TEST_DATABASE_PATTERN.test(sourceDatabase) ||
    !TEST_DATABASE_PATTERN.test(targetDatabase) ||
    sourceDatabase === targetDatabase
  ) {
    throw genericFailure("Logical dump targets must be distinct invocation-owned test databases.");
  }

  const dumpDirectory = path.join(localRoot, "dumps");
  await assertNotSymlink(dumpDirectory, "Local PostgreSQL dump directory");
  await mkdir(dumpDirectory, { mode: 0o700, recursive: true });
  await chmod(dumpDirectory, 0o700);
  const dumpPath = path.join(dumpDirectory, `${sourceDatabase}-${targetDatabase}.dump`);
  await assertNotSymlink(dumpPath, "Local PostgreSQL logical dump");
  const dumpEnvironment = { PGPASSWORD: runtime.credentials.adminPassword };
  const restoreEnvironment = { PGPASSWORD: runtime.credentials.migratorPassword };

  try {
    await sourceHandle.attest();
    await targetHandle.attest();
    const admin = await connectAttested(runtime, "postgres");
    try {
      const ownership = await admin.query(
        "SELECT datname, pg_get_userbyid(datdba) AS owner FROM pg_database WHERE datname = ANY($1::text[])",
        [[sourceDatabase, targetDatabase]],
      );
      if (ownership.rowCount !== 2 || ownership.rows.some(({ owner }) => owner !== MIGRATOR_ROLE)) {
        throw genericFailure("Logical dump database ownership is unexpected.");
      }
    } finally {
      await admin.end();
    }
    const target = createClient(runtime, targetDatabase, APP_ROLE);
    await target.connect();
    try {
      const relations = await target.query(`
        SELECT count(*)::int AS count
          FROM pg_class AS relation
          JOIN pg_namespace AS namespace ON namespace.oid = relation.relnamespace
         WHERE namespace.nspname NOT IN ('pg_catalog', 'information_schema')
           AND namespace.nspname !~ '^pg_toast'
           AND relation.relkind IN ('r', 'p', 'v', 'm', 'S', 'f')
      `);
      if (relations.rows[0]?.count !== 0) {
        throw genericFailure("Logical restore target is not empty.");
      }
    } finally {
      await target.end();
    }
    runCommand(
      runtime.binaries.pg_dump,
      [
        "--host",
        HOST,
        "--port",
        String(PORT),
        "--username",
        ADMIN_ROLE,
        "--dbname",
        sourceDatabase,
        "--format",
        "custom",
        "--enable-row-security",
        "--inserts",
        "--file",
        dumpPath,
        "--no-owner",
        "--no-acl",
      ],
      { env: dumpEnvironment, timeout: 120_000 },
    );
    await chmod(dumpPath, 0o600);
    runCommand(
      runtime.binaries.pg_restore,
      [
        "--host",
        HOST,
        "--port",
        String(PORT),
        "--username",
        MIGRATOR_ROLE,
        "--dbname",
        targetDatabase,
        "--exit-on-error",
        "--single-transaction",
        "--enable-row-security",
        "--no-owner",
        "--no-acl",
        dumpPath,
      ],
      { env: restoreEnvironment, timeout: 120_000 },
    );
    await ensureRuntimeDatabasePrivileges(runtime, targetDatabase);
  } finally {
    await rm(dumpPath, { force: true });
  }
};

